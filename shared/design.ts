interface SectionBase {
  /** Stable within a design. It is what the error boundary NAMES when this
   *  section is the one that threw, so it survives reordering and renaming. */
  id: string;
  kind: SectionKind;
  /** Kept in the config, skipped by the renderer. A hidden section is how an
   *  author tries something without losing it — the same "retained while
   *  inactive" rule the whole design file follows, one level down. */
  hidden?: boolean;
}

export interface HeroSection extends SectionBase {
  kind: "hero";
  /** Empty → the site name, so a hero costs no typing to be useful. */
  heading: string;
  sub: string;
  /** https URL or a vault-relative image path, exactly like `settings.logo`. */
  image: string | null;
  align: "start" | "center";
  height: "short" | "tall";
  /** WHAT SHAPE THE OPENING IS, which the first three fields could not say.
   *  `panel` is the rounded card the hero has always been. `band` is a field
   *  of ground and type running the full column with square corners — the
   *  opening for a site that has no photograph and does not want a generated
   *  one. `split` sets the words against the picture instead of on top of it,
   *  which is the arrangement a scrim cannot produce.
   *
   *  `cover` IS THE ONE THAT BREAKS THE COLUMN, and it is here because the
   *  stock blog's own dashboard has had it since before this engine existed: a
   *  photograph running the FULL WIDTH OF THE WINDOW with the site's name over
   *  it. Every other treatment lives inside `--dsn-width`, which meant the one
   *  opening a Vellum site most often already has was the one thing a design
   *  could not reproduce — an author who liked their front page could not start
   *  from it. It is the only section in the engine that leaves the column, it
   *  says so in its name, and `design.css` carries the full-bleed idiom (a
   *  negative logical margin against the page's own padding) in one place. */
  treatment: "panel" | "band" | "split" | "cover";
}

export interface RichTextSection extends SectionBase {
  kind: "richText";
  /** Rendered through the reading renderer — the same sanitizer, the same
   *  wikilink resolution, the same callouts. Authoring the public homepage in
   *  markdown is the point; inventing a second content format is not. */
  markdown: string;
  align: "start" | "center";
}

export interface NoteSection extends SectionBase {
  kind: "note";
  /** Vault-relative `.md` path. THE section that can point at a note the
   *  author later deletes or unpublishes — see the boundary. */
  note: string;
  heading: string;
  /** Show the first paragraph only, with a link through to the note. */
  excerpt: boolean;
}

export interface PostGridSection extends SectionBase {
  kind: "postGrid";
  heading: string;
  limit: number;
  columns: number;
  /** Restrict to one tag; empty = every published post. */
  tag: string;
  showExcerpt: boolean;
  showBanner: boolean;
  showDate: boolean;
  /** THE CARD'S ANATOMY, which was one shape for every design on the shelf.
   *  `boxed` is the bordered tile on raised ground. `bare` deletes the box and
   *  lets the picture and the words stand on the page. `overlay` puts the
   *  title on a scrim over the picture. `ledger` turns the tile on its side —
   *  thumbnail at the start, words at the end. `masonry` drops the grid for
   *  CSS columns so pictures keep their own proportions. */
  card: "boxed" | "bare" | "overlay" | "ledger" | "masonry";
}

export interface PostListSection extends SectionBase {
  kind: "postList";
  heading: string;
  limit: number;
  tag: string;
  showExcerpt: boolean;
  showDate: boolean;
  /** HOW THE RUN IS SET, and the reason every design on the shelf listed its
   *  writing the same way. `river` is the stacked title-meta-excerpt run this
   *  section shipped as. `ledger` rules every row and hangs the date in a
   *  column of its own. `index` is a table of contents — title, leader, date,
   *  nothing else. `numbered` counts the entries in oversized faint ordinals.
   *  `dateline` groups the run under the day it was published, the way a paper
   *  does. None of them decides a colour; all of them decide an arrangement. */
  layout: "river" | "ledger" | "index" | "numbered" | "dateline";
}

export interface TopicsSection extends SectionBase {
  kind: "topics";
  heading: string;
  limit: number;
}

export interface CtaSection extends SectionBase {
  kind: "cta";
  heading: string;
  body: string;
  label: string;
  /** Site-relative ("/topic/x") or an absolute https URL. Nothing else — a
   *  homepage button is not a place to accept `javascript:`. */
  url: string;
}

export interface DividerSection extends SectionBase {
  kind: "divider";
  /** `ornament` is the reading view's own `***` divider, drawn by the same
   *  idiom: an accent rule that fades at both ends with the wordmark's ✦ over
   *  a gap in the middle. A composed page breaks its run of sections for the
   *  same reason an essay breaks its run of paragraphs, and it should not have
   *  had to do it with a chrome hairline. */
  style: "rule" | "dots" | "ornament" | "blank";
  /** Vertical air, in px. */
  space: number;
}

export type Section =
  | HeroSection
  | RichTextSection
  | NoteSection
  | PostGridSection
  | PostListSection
  | TopicsSection
  | CtaSection
  | DividerSection;

