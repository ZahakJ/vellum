// ── Validation ──────────────────────────────────────────────────────────────

/** Every rejection this module makes. `path` names the offending place inside
 *  the document ("sections[2].limit"), which is what the admin notice prints
 *  and what makes a hand-edited file fixable without a debugger. */
export class DesignError extends Error {
  readonly path: string;
  constructor(path: string, message: string) {
    super(path ? `${path}: ${message}` : message);
    this.path = path;
  }
}

/** Thrown when a document cannot be understood by this build AT ALL and must
 *  be kept, not repaired. Separate from DesignError because the outcomes
 *  differ: a DesignError is a 400 on a write and a skipped row on a read; a
 *  QuarantineError is always a kept-but-inert row with a message. */
export class QuarantineError extends Error {}

function asObject(value: unknown, path: string): Record<string, unknown> {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    throw new DesignError(path, "must be an object");
  }
  return value as Record<string, unknown>;
}

/** Single-line, control characters and bidi overrides stripped, capped.
 *  Bidi stripping is the `shared/bidi.ts` rule: this text is authored by the
 *  operator but it renders into the PUBLIC page beside note titles, and an
 *  RLO in a heading reorders everything after it. */
function text(value: unknown, path: string, max: number, fallback = ""): string {
  if (value === undefined || value === null) return fallback;
  if (typeof value !== "string") throw new DesignError(path, "must be a string");
  const clean = stripBidiControls(value).replace(/[\u0000-\u001f\u007f]+/g, " ").trim();
  if (clean.length > max) throw new DesignError(path, `is too long (${max} characters max)`);
  return clean;
}

/** Multi-line: newlines survive, control characters and bidi overrides do
 *  not. The one field this is for is a section's markdown body. */
function block(value: unknown, path: string, max: number): string {
  if (value === undefined || value === null) return "";
  if (typeof value !== "string") throw new DesignError(path, "must be a string");
  const clean = stripBidiControls(value).replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]+/g, "");
  if (clean.length > max) throw new DesignError(path, `is too long (${max} characters max)`);
  return clean;
}

function bool(value: unknown, path: string, fallback: boolean): boolean {
  if (value === undefined || value === null) return fallback;
  if (typeof value !== "boolean") throw new DesignError(path, "must be true or false");
  return value;
}

function int(value: unknown, path: string, min: number, max: number, fallback: number): number {
  if (value === undefined || value === null) return fallback;
  if (typeof value !== "number" || !Number.isFinite(value)) {
    throw new DesignError(path, "must be a number");
  }
  const n = Math.round(value);
  if (n < min || n > max) throw new DesignError(path, `must be between ${min} and ${max}`);
  return n;
}

function oneOf<T extends string>(
  value: unknown,
  path: string,
  allowed: readonly T[],
  fallback: T,
): T {
  if (value === undefined || value === null) return fallback;
  if (typeof value !== "string" || !(allowed as readonly string[]).includes(value)) {
    throw new DesignError(path, `must be one of: ${allowed.join(", ")}`);
  }
  return value as T;
}

/** An image reference: an https URL or a vault-relative image path. The same
 *  rule `settings.logo` follows, and for the same reason — this lands in an
 *  `<img src>` on every visitor's homepage. `http:`, `data:` and `javascript:`
 *  are named rejections rather than falling through to path normalization,
 *  which would mangle a URL into a broken vault path and hide the mistake. */
const IMAGE_EXT = /\.(ico|png|svg|jpe?g|gif|webp|avif)$/i;
function imageRef(value: unknown, path: string): string | null {
  if (value === undefined || value === null || value === "") return null;
  const raw = text(value, path, URL_MAX);
  if (raw === "") return null;
  if (/^https:\/\//i.test(raw)) return raw;
  if (/^[a-z][a-z0-9+.-]*:/i.test(raw)) {
    throw new DesignError(path, "must be an https:// URL or a vault image path");
  }
  const rel = raw.replace(/\\/g, "/").replace(/^\/+/, "");
  if (rel === "" || rel.split("/").some((seg) => seg === "." || seg === "..")) {
    throw new DesignError(path, "is not a valid vault path");
  }
  if (!IMAGE_EXT.test(rel)) {
    throw new DesignError(path, "must be an image (ico, png, svg, jpeg, gif, webp, avif)");
  }
  return rel;
}

/** A link target: site-relative, or an absolute https URL. A homepage button
 *  is not a place that accepts `javascript:` — and "we sanitize it later" is
 *  how one eventually ships. */
function linkRef(value: unknown, path: string): string {
  const raw = text(value, path, URL_MAX, "/");
  if (raw === "") return "/";
  if (/^https:\/\//i.test(raw)) return raw;
  if (raw.startsWith("/") && !raw.startsWith("//")) return raw;
  throw new DesignError(path, "must be a site path starting with / or an https:// URL");
}

/** A vault-relative markdown path. */
function notePath(value: unknown, path: string): string {
  const raw = text(value, path, URL_MAX);
  if (raw === "") return "";
  const rel = raw.replace(/\\/g, "/").replace(/^\/+/, "");
  if (rel.split("/").some((seg) => seg === "." || seg === "..")) {
    throw new DesignError(path, "is not a valid vault path");
  }
  if (!/\.md$/i.test(rel)) throw new DesignError(path, "must be a markdown path (….md)");
  return rel;
}

const SLUG_RE = /^[a-z0-9][a-z0-9-]{0,63}$/;

export function slugifyDesignName(name: string): string {
  const slug = name
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 48);
  return slug === "" ? "design" : slug;
}

/** Validate one section. STRICT: an unknown `kind` and an unknown KEY are
 *  both errors naming the offender. Returns a fresh object carrying only
 *  allowlisted keys, so nothing unvalidated survives into the file. */
export function validateSection(input: unknown, path: string, index: number): Section {
  const raw = asObject(input, `${path}[${index}]`);
  const at = `${path}[${index}]`;
  const kind = raw.kind;
  if (typeof kind !== "string" || !SECTION_KINDS.includes(kind as SectionKind)) {
    throw new DesignError(`${at}.kind`, `must be one of: ${SECTION_KINDS.join(", ")}`);
  }
  const id = typeof raw.id === "string" && SLUG_RE.test(raw.id) ? raw.id : `s${index + 1}`;
  const hidden = bool(raw.hidden, `${at}.hidden`, false);

  const allowed = new Set(["id", "kind", "hidden", ...KIND_KEYS[kind as SectionKind]]);
  for (const key of Object.keys(raw)) {
    if (!allowed.has(key)) throw new DesignError(`${at}.${key}`, "is not a key this section has");
  }

  const base = { id, kind: kind as SectionKind, ...(hidden ? { hidden: true } : {}) };
  switch (kind as SectionKind) {
    case "hero":
      return {
        ...base,
        kind: "hero",
        heading: text(raw.heading, `${at}.heading`, HEADING_MAX),
        sub: text(raw.sub, `${at}.sub`, SUB_MAX),
        image: imageRef(raw.image, `${at}.image`),
        align: oneOf(raw.align, `${at}.align`, ["start", "center"] as const, "center"),
        height: oneOf(raw.height, `${at}.height`, ["short", "tall"] as const, "short"),
        treatment: oneOf(
          raw.treatment,
          `${at}.treatment`,
          ["panel", "band", "split", "cover"] as const,
          "panel",
        ),
      };
    case "richText":
      return {
        ...base,
        kind: "richText",
        markdown: block(raw.markdown, `${at}.markdown`, MARKDOWN_MAX),
        align: oneOf(raw.align, `${at}.align`, ["start", "center"] as const, "start"),
      };
    case "note":
      return {
        ...base,
        kind: "note",
        note: notePath(raw.note, `${at}.note`),
        heading: text(raw.heading, `${at}.heading`, HEADING_MAX),
        excerpt: bool(raw.excerpt, `${at}.excerpt`, false),
      };
    case "postGrid":
      return {
        ...base,
        kind: "postGrid",
        heading: text(raw.heading, `${at}.heading`, HEADING_MAX),
        limit: int(raw.limit, `${at}.limit`, 1, 48, 6),
        columns: int(raw.columns, `${at}.columns`, 1, 4, 2),
        tag: text(raw.tag, `${at}.tag`, 64),
        showExcerpt: bool(raw.showExcerpt, `${at}.showExcerpt`, true),
        showBanner: bool(raw.showBanner, `${at}.showBanner`, true),
        showDate: bool(raw.showDate, `${at}.showDate`, true),
        card: oneOf(
          raw.card,
          `${at}.card`,
          ["boxed", "bare", "overlay", "ledger", "masonry"] as const,
          "boxed",
        ),
      };
    case "postList":
      return {
        ...base,
        kind: "postList",
        heading: text(raw.heading, `${at}.heading`, HEADING_MAX),
        limit: int(raw.limit, `${at}.limit`, 1, 200, 20),
        tag: text(raw.tag, `${at}.tag`, 64),
        showExcerpt: bool(raw.showExcerpt, `${at}.showExcerpt`, true),
        showDate: bool(raw.showDate, `${at}.showDate`, true),
        layout: oneOf(
          raw.layout,
          `${at}.layout`,
          ["river", "ledger", "index", "numbered", "dateline"] as const,
          "river",
        ),
      };
    case "topics":
      return {
        ...base,
        kind: "topics",
        heading: text(raw.heading, `${at}.heading`, HEADING_MAX),
        limit: int(raw.limit, `${at}.limit`, 1, 60, 12),
      };
    case "cta":
      return {
        ...base,
        kind: "cta",
        heading: text(raw.heading, `${at}.heading`, HEADING_MAX),
        body: text(raw.body, `${at}.body`, SUB_MAX),
        label: text(raw.label, `${at}.label`, 60),
        url: linkRef(raw.url, `${at}.url`),
      };
    case "divider":
      return {
        ...base,
        kind: "divider",
        style: oneOf(
          raw.style,
          `${at}.style`,
          ["rule", "dots", "ornament", "blank"] as const,
          "rule",
        ),
        space: int(raw.space, `${at}.space`, 0, 240, 32),
      };
  }
}

