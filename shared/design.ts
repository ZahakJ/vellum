// The design config: what "designed" mode renders instead of the stock blog.
//
// ARCHITECTURE, and it is the non-negotiable part. The built-in blog is a
// PRISTINE, SEPARATE, ALWAYS-WORKING BASE. Nothing in this module, in
// server/designs.ts, or in client/design/ mutates, forks, subclasses,
// monkey-patches or re-styles a single stock blog component or a single rule
// in blog.css. `publicLayout` gains a third value and the client grows a
// SECOND renderer beside the first; the two never meet except at one `if`.
// A reviewer confirms that from the diff by checking that client/blog/* and
// client/styles/blog.css are untouched — they are.
//
// The consequence that makes the switch worth having: it is LOSSLESS BOTH
// WAYS. The design lives in its own file and is never consulted while
// `publicLayout` is anything but "designed", so flipping back to stock is a
// RESCUE (nothing is deleted, nothing is migrated, nothing is lost) and
// flipping forward again returns the site exactly as it was. That is also the
// one-click escape the error boundary offers an admin whose design is broken.
//
// This module is the SHAPE — types, the allowlist, per-key validation,
// migration and the stock defaults. It is shared because both sides need the
// same answer: the server validates on write, and the CLIENT validates again
// on read before it renders a byte, so a file that was hand-edited past the
// server (settings.json's own documented escape hatch, one directory up)
// still cannot put a malformed section in front of a visitor.

